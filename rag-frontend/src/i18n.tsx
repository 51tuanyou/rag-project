export function localizeLog(line: string, lang: Lang) {
  if (lang !== 'en') return line
  const parts = line.split('\n')
  return parts.map((part) => {
    for (const [pattern, template] of LOG_RULES) {
      const match = part.match(pattern)
      if (!match) continue
      return template.replace(/\$(\d+)/g, (_, index) => match[Number(index)] ?? '')
    }
    return part
  }).join('\n')
}
