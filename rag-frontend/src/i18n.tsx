const dictionaries: Record<Lang, { [K in I18nKey]: string }> = { en, zh }

type I18nContextValue = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: I18nKey, vars?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function readLang(): Lang {
  const saved = localStorage.getItem('ui.language')
  return saved === 'zh' || saved === 'en' ? saved : 'en'
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)
  const setLang = (next: Lang) => {
    localStorage.setItem('ui.language', next)
    setLangState(next)
  }
  const value = useMemo<I18nContextValue>(() => {
    const t = (key: I18nKey, vars?: Record<string, string | number>) => {
      let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key
      if (vars) {
        for (const [name, replacement] of Object.entries(vars)) {
          text = text.replaceAll(`{${name}}`, String(replacement))
        }
      }
      return text
    }
    return { lang, setLang, t }
  }, [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used within LanguageProvider')
  return value
}

export function AppTitle() {
  const { lang, setLang, t } = useI18n()
  return (
    <Box sx={{ display: 'grid', gridTemplateColumns: '1fr auto 1fr', alignItems: 'center', mb: 3, minHeight: 40, columnGap: 2 }}>
      <Box />
      <Typography variant="h4" component="h1" sx={{ fontWeight: 600, color: 'primary.main', textAlign: 'center', whiteSpace: 'nowrap' }}>
        {t('appTitle')}
      </Typography>
      <ToggleButtonGroup
        exclusive
        size="small"
        value={lang}
        onChange={(_, next: Lang | null) => {
          if (next) setLang(next)
        }}
        sx={{ justifySelf: 'end' }}
      >
        <ToggleButton value="en">English</ToggleButton>
        <ToggleButton value="zh">中文</ToggleButton>
      </ToggleButtonGroup>
    </Box>
  )
}

